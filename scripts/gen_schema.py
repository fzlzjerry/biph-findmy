"""Generate supabase/migrations/0001_init.sql from the SQLAlchemy models.

    uv run python scripts/gen_schema.py

The models in backend/app/models.py are the single source of truth. The generated migration
also locks the tables down for Supabase: Row Level Security on, no access for the public
`anon` / `authenticated` API roles, and full access only for the backend's own `app_backend`
role (its password is set separately and never stored in the repo).
"""

from __future__ import annotations

import sys
from pathlib import Path

from sqlalchemy.dialects import postgresql
from sqlalchemy.schema import CreateIndex, CreateTable

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from backend.app.models import Base  # noqa: E402

OUT = ROOT / "supabase" / "migrations" / "0001_init.sql"


def main() -> None:
    dialect = postgresql.dialect()
    lines = [
        "-- Generated by scripts/gen_schema.py from backend/app/models.py — do not edit by hand.",
        "",
        "do $$ begin",
        "  if not exists (select from pg_roles where rolname = 'app_backend') then",
        "    create role app_backend nologin noinherit;",
        "  end if;",
        "end $$;",
        "",
    ]
    for table in Base.metadata.sorted_tables:
        ddl = str(CreateTable(table).compile(dialect=dialect)).strip()
        lines.append(ddl.replace("CREATE TABLE ", "CREATE TABLE IF NOT EXISTS ", 1) + ";")
        for index in sorted(table.indexes, key=lambda i: i.name):
            idx = str(CreateIndex(index).compile(dialect=dialect)).strip()
            lines.append(idx.replace("CREATE INDEX ", "CREATE INDEX IF NOT EXISTS ", 1)
                         .replace("CREATE UNIQUE INDEX ", "CREATE UNIQUE INDEX IF NOT EXISTS ", 1) + ";")
        name = table.name
        lines += [
            f"ALTER TABLE {name} ENABLE ROW LEVEL SECURITY;",
            f"REVOKE ALL ON TABLE {name} FROM anon, authenticated;",
            f"GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE {name} TO app_backend;",
            f"DROP POLICY IF EXISTS app_backend_all ON {name};",
            f"CREATE POLICY app_backend_all ON {name} FOR ALL TO app_backend USING (true) WITH CHECK (true);",
            "",
        ]
    lines += [
        "GRANT USAGE ON SCHEMA public TO app_backend;",
        "GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO app_backend;",
        "",
    ]
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
